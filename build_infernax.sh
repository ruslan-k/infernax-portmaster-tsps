#!/usr/bin/env bash
# Build the Infernax native Horizon adapter from the recovered baseline.
# The owner image (module segments + RomFS section + generated contracts) is an input;
# no game payload is packaged into this repository.
#
# Usage: build_infernax.sh RECOVERED_SOURCE OWNER_IMAGE NEW_OUTPUT [OUTPUT_NAME]
set -euo pipefail
if [[ $# -lt 3 || $# -gt 4 ]]; then
    printf 'Usage: %s RECOVERED_SOURCE OWNER_IMAGE NEW_OUTPUT [OUTPUT_NAME]\n' "$0" >&2
    exit 64
fi
source_root=$(realpath "$1")
image=$(realpath "$2")
output=$(realpath -m "$3")
output_name=${4:-infernax-nextos}
recipe=$(cd "$(dirname "$0")" && pwd)
[[ ! -e "$output" ]] || { printf 'NEW_OUTPUT already exists: %s\n' "$output" >&2; exit 65; }
mkdir -p "$output/source"
cp -a "$source_root/native" "$source_root/framework" "$output/source/"
work="$output/source"
if [[ -f "$recipe/runtime/infernax-adapter.patch" ]]; then
    git -C "$work" init -q
    git -C "$work" apply --check "$recipe/runtime/infernax-adapter.patch"
    git -C "$work" apply "$recipe/runtime/infernax-adapter.patch"
fi
: "${COTM_CC:=aarch64-linux-gnu-gcc}"
export COTM_CC
export COTM_NXINPUT_DIR="$work/framework/nxinput"
export COTM_NXCOMPAT_DIR="$work/framework/nxcompat"
export COTM_NXGL_DIR="$work/framework/nxgl"
export COTM_NXLOADER_DIR="$work/framework/nxloader"
export COTM_SDL_INCLUDE_DIR=/usr/include/SDL2
# Static nxaudio provider (pinned framework source, built here).
provider="$output/provider-build/nxaudio"
mkdir -p "$provider"
cp "$work/framework/nxaudio/include/"*.h "$provider/"
for name in nxaudio nxaudio_receipt nxaudio_runtime; do
    "$COTM_CC" -O2 -g -fno-omit-frame-pointer -fPIC -pthread -std=c11 -D_POSIX_C_SOURCE=200809L \
        -I"$provider" -c "$work/framework/nxaudio/src/$name.c" -o "$provider/$name.o"
done
aarch64-linux-gnu-ar rcs "$provider/libnxaudio.a" "$provider/"*.o
export COTM_NXAUDIO_DIR="$provider"
# Shader catalogue: our own translations, generated by tools/build_infernax_catalogue.py.
# Absent catalogue = the baseline's empty stub (the runtime then stops on the first program).
if [[ -f "$recipe/runtime/infernax-shaders-draft.h" ]]; then
    shaders="$output/shaders"
    mkdir -p "$shaders"
    cp "$recipe/runtime/infernax-shaders-draft.h" "$shaders/nvn_shader_sources.h"
    export COTM_SHADERS_DIR="$shaders"
fi
export TMPDIR="$output/scratch"
mkdir -p "$TMPDIR"
bash "$work/native/build.sh" "$image" "$output/native-build"
mv "$output/native-build/terminator2d-nextos" "$output/$output_name"
# Mandatory paired launcher helper; the launcher refuses an incomplete install.
cp "$recipe/tools/run_identity.py" "$output/run_identity.py"
sha256sum "$output/$output_name" "$output/run_identity.py"
